#Requires -Version 7.0

param(
    [Parameter(Mandatory)]
    [string[]]$LibDirectories,

    [Parameter(Mandatory)]
    [string[]]$DllDirectories,

    [Parameter(Mandatory)]
    [string]$SdkVersion,

    [string[]]$LibraryMappings = @(
        "$PSScriptRoot\..\generation\WinSDK\libMappings.rsp",
        "$PSScriptRoot\..\generation\WinSDK\libMappingsManual.rsp"
    ),

    [string]$OutputFile = "$PSScriptRoot\..\generation\WinSDK\importEntryPoints.rsp",

    [string]$MetadataUtilsPath = "$PSScriptRoot\..\bin\Release\net10.0\MetadataUtils.dll"
)

$ErrorActionPreference = 'Stop'
Add-Type -Path (Resolve-Path $MetadataUtilsPath)
$libPaths = @($LibDirectories | ForEach-Object { (Resolve-Path $_).Path })
$dllPaths = @($DllDirectories | ForEach-Object { (Resolve-Path $_).Path })
$mappings = @{}
foreach ($mappingFile in $LibraryMappings)
{
    foreach ($line in [IO.File]::ReadLines((Resolve-Path $mappingFile)))
    {
        if ($line -match '^([^#=]+)=([^=]+)$')
        {
            $mappings[$Matches[1]] = [IO.Path]::GetFileNameWithoutExtension($Matches[2])
        }
    }
}

$dllCache = @{}
$entries = [Collections.Generic.SortedDictionary[string,string]]::new([StringComparer]::Ordinal)
$sources = [Collections.Generic.SortedDictionary[string,string]]::new([StringComparer]::Ordinal)
$missing = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$unconfirmed = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)

foreach ($libPath in $libPaths)
{
    foreach ($lib in Get-ChildItem $libPath -Filter '*.lib' | Sort-Object Name)
    {
        foreach ($info in [MetadataUtils.LibScraper]::GetImportInfos($lib.FullName))
        {
            if ($null -eq $info.Ordinal -or
                $mappings[$info.ProcName] -ne [IO.Path]::GetFileNameWithoutExtension($info.Dll))
            {
                continue
            }

            if (!$dllCache.ContainsKey($info.Dll))
            {
                $dllCache[$info.Dll] = $null
                foreach ($dllPath in $dllPaths)
                {
                    $path = Join-Path $dllPath $info.Dll
                    if (Test-Path $path -PathType Leaf)
                    {
                        $dllCache[$info.Dll] = @{
                            Names = [MetadataUtils.DllExports]::GetNamedExports($path)
                            Ordinals = [MetadataUtils.DllExports]::GetOrdinalOnlyExports($path)
                            Version = [Diagnostics.FileVersionInfo]::GetVersionInfo($path).FileVersion
                            Hash = (Get-FileHash $path -Algorithm SHA256).Hash.ToLowerInvariant()
                        }
                        break
                    }
                }
            }

            $dll = $dllCache[$info.Dll]
            if ($null -eq $dll)
            {
                [void]$missing.Add($info.Dll.ToLowerInvariant())
                continue
            }
            if ($dll.Names.Contains($info.ProcName))
            {
                continue
            }
            if (!$dll.Ordinals.Contains($info.Ordinal))
            {
                [void]$unconfirmed.Add("$($info.ProcName)=$($info.Dll)#$($info.Ordinal)")
                continue
            }

            if ($entries.ContainsKey($info.ProcName) -and $entries[$info.ProcName] -ne $info.EntryPoint)
            {
                throw "Conflicting architecture ordinals for $($info.ProcName): $($entries[$info.ProcName]) and $($info.EntryPoint)."
            }
            $entries[$info.ProcName] = $info.EntryPoint
            $sources[$info.Dll.ToLowerInvariant()] = "$($dll.Version); SHA256 $($dll.Hash)"
        }
    }
}

if ($entries.Count -eq 0)
{
    throw 'No confirmed ordinal-only imports found. The existing snapshot was not replaced.'
}

$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# Generated by scripts\CreateImportEntryPoints.ps1. Regenerate when updating the SDK.')
$lines.Add("# Import libraries: SDK $SdkVersion. DLL versions below describe the actual snapshot, not SDK equivalence.")
$lines.Add('# Only mapped imports whose ordinal is populated and unnamed in the source DLL are included.')
$lines.Add('# Missing DLLs and absent ordinals are omitted; they retain the previous by-name behavior.')
foreach ($source in $sources.GetEnumerator())
{
    $lines.Add("# $($source.Key): $($source.Value)")
}
$lines.Add('--importEntryPoint')
foreach ($entry in $entries.GetEnumerator())
{
    $lines.Add("$($entry.Key)=$($entry.Value)")
}

[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutputFile), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
if ($missing.Count)
{
    Write-Warning ("DLLs not found: " + (($missing | Sort-Object) -join ', '))
}
if ($unconfirmed.Count)
{
    Write-Warning ("Unconfirmed ordinals omitted: " + (($unconfirmed | Sort-Object) -join ', '))
}
$size = (Get-Item $OutputFile).Length
Write-Host "$($entries.Count) mappings, $($sources.Count) source DLLs, $size bytes ($([Math]::Round($size / 1KB, 2)) KiB)."
